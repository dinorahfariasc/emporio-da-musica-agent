"""Renders docs/data-quality-report.md from the in-memory payload (no database, deterministic)."""

from collections import defaultdict

from etl.rules import ANOMALY_TYPES, Derived

DL001_TRACEABILITY: list[tuple[str, str]] = [
    ("135–144 name contradicts description", "`untrusted_description`"),
    (
        "135–144 specs contradict description (5 vs 4 strings, 88 vs 61 keys)",
        "`untrusted_description` (specs win)",
    ),
    ("`specs` JSON schema varies by category", "Enforced by validation (per-category schema)"),
    ("96 active with zero stock", "`out_of_stock_active`"),
    ("113 discontinued", "`discontinued`"),
    ("136 discontinued with 13 units", "`discontinued`"),
    ("130 coming_soon yet present in orders", "`coming_soon` + `not_on_sale_in_order`"),
    ("Duplicate promotions per product (96: 18% and 40%)", "`duplicate_promotions`"),
    ("Only 4 promotions active", "`active_promotions`"),
    ("Promotions have no validity dates", "`no_promotion_validity_dates`"),
    ("Order totals differ from item sums (3, 20)", "`order_total_mismatch`"),
    (
        '"Ponta Porã" in two encodings',
        "`nfc_normalized` (CRLF artefact; CRLF parsing enforced by validation and tested)",
    ),
    ("Customers 11 and 43 share an email", "`shared_email`"),
    ("Two WhatsApp numbers (§1.2 vs §7)", "`policy_conflict`"),
    ("Email with and without accent", "`policy_conflict`"),
    ("Installment table contradicts §3.1", "`policy_conflict`"),
    ("7-day withdrawal only online; orders lack the channel", "`missing_purchase_channel`"),
    ("*(new)* Categories 6–8 have no products", "`empty_category`"),
    ("*(new)* Empty optional order fields (orders 9–20)", "Enforced by validation (`''` → NULL)"),
]


def render(payload: Derived) -> str:
    by_type = defaultdict(list)
    for anomaly in payload.anomalies:
        by_type[anomaly.type].append(anomaly)

    lines = [
        "# Data Quality Report",
        "",
        "> Generated by `python -m etl`. Do not edit.",
        "",
        "## Summary",
        "",
        "| Anomaly | Entity | Count | Rule |",
        "|---|---|---|---|",
    ]
    for name, kind in ANOMALY_TYPES.items():
        lines.append(f"| {name} | {kind.entity} | {len(by_type[name])} | {kind.rule} |")

    lines += ["", "## DL-001 traceability", "", "| Finding | Handled by |", "|---|---|"]
    lines += [f"| {finding} | {handled} |" for finding, handled in DL001_TRACEABILITY]

    lines += ["", "## Details"]
    for name, kind in ANOMALY_TYPES.items():
        if not by_type[name]:
            continue
        lines += ["", f"### {name}", "", kind.description, "", "| Record | Detail |", "|---|---|"]
        lines += [f"| {a.record} | {a.detail} |" for a in by_type[name]]

    lines += ["", "## Load summary", "", "| Table | Rows |", "|---|---|"]
    lines += [f"| {table} | {len(rows)} |" for table, rows in payload.tables.items()]
    return "\n".join(lines) + "\n"
